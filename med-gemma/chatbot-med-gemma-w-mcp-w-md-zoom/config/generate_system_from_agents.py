"""Regenerate application Python files from source blocks in md/AGENTS.md.

AGENTS.md is both the behavioral contract and canonical versioned source store;
generation never reads a ``.py.old`` template.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AGENTS = ROOT / "md" / "AGENTS.md"
GENERATED = tuple(ROOT / "python" / name for name in (
    "client_medgemma_patients_mcp.py", "mcp_client.py", "mcp_record_server.py",
    "mcp_xray_server.py", "mcp_ekg_server.py", "mcp_blood_server.py",
))
REQUIRED_RULES = ("Authoritative implementation", "Keep `mcp_client.py` separate", "Top bar: First name", "Servers must preserve path confinement")
SOURCE_START = "<!-- GENERATED-PYTHON-SOURCES: START -->"
SOURCE_END = "<!-- GENERATED-PYTHON-SOURCES: END -->"


def validate_contract(description: str) -> None:
    missing = [rule for rule in REQUIRED_RULES if rule not in description]
    if missing:
        raise ValueError("AGENTS.md is missing required system rules: " + ", ".join(missing))


def extract_sources(description: str) -> dict[Path, str]:
    """Read fenced Python blocks headed by ``### python/<name>.py``."""
    if SOURCE_START not in description or SOURCE_END not in description:
        raise ValueError("AGENTS.md has no canonical Python source section")
    section = description.split(SOURCE_START, 1)[1].split(SOURCE_END, 1)[0]
    found = re.findall(r"^### `(python/[^`]+\.py)`\r?\n```python\r?\n(.*?)^```\s*$", section, re.MULTILINE | re.DOTALL)
    sources = {(ROOT / relative).resolve(): source.replace("\r\n", "\n") for relative, source in found}
    unknown = [str(path) for path in sources if path not in GENERATED]
    if unknown:
        raise ValueError("Unexpected generated source in AGENTS.md: " + ", ".join(unknown))
    missing = [str(target.relative_to(ROOT)) for target in GENERATED if target not in sources]
    if missing:
        raise ValueError("AGENTS.md is missing Python source blocks: " + ", ".join(missing))
    return sources


def import_current_sources() -> None:
    """One-time migration of existing runnable files into AGENTS.md."""
    description = AGENTS.read_text(encoding="utf-8-sig")
    if SOURCE_START in description:
        raise ValueError("AGENTS.md already contains canonical Python sources")
    blocks = [SOURCE_START, "", "## Canonical generated Python sources", ""]
    for target in GENERATED:
        if not target.is_file():
            raise FileNotFoundError(f"Missing current source for migration: {target}")
        source = target.read_text(encoding="utf-8-sig")
        source = re.sub(r"(?:^# GENERATED.*\n|^# Preserved.*\n|^# Regenerate.*\n|^# Source requirements:.*\n|^\n)+", "", source)
        blocks.extend((f"### `{target.relative_to(ROOT).as_posix()}`", "```python", source.rstrip("\n"), "```", ""))
    blocks.append(SOURCE_END)
    AGENTS.write_text(description.rstrip() + "\n\n" + "\n".join(blocks) + "\n", encoding="utf-8", newline="\n")
    print("[COMPLETE] Imported canonical Python sources into md/AGENTS.md")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--import-current", action="store_true", help="migrate current runnable files into AGENTS.md")
    args = parser.parse_args()
    if not AGENTS.is_file():
        raise FileNotFoundError(f"Missing system description: {AGENTS}")
    if args.import_current:
        import_current_sources()
    description = AGENTS.read_text(encoding="utf-8-sig")
    validate_contract(description)
    for target, source in extract_sources(description).items():
        target.write_text("# GENERATED FROM md/AGENTS.md. DO NOT EDIT THIS FILE DIRECTLY.\n\n" + source.lstrip("\n"), encoding="utf-8", newline="\n")
        print(f"[COMPLETE] Generated {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
