"""Regenerate the GUI from the canonical source held in md/AGENTS.md."""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "config"))
from generate_system_from_agents import AGENTS, extract_sources, validate_contract  # noqa: E402


def main() -> int:
    description = AGENTS.read_text(encoding="utf-8-sig")
    validate_contract(description)
    target = ROOT / "python" / "client_medgemma_patients_mcp.py"
    source = extract_sources(description)[target]
    target.write_text("# GENERATED FROM md/AGENTS.md. DO NOT EDIT THIS FILE DIRECTLY.\n\n" + source.lstrip("\n"), encoding="utf-8", newline="\n")
    print(f"[COMPLETE] Generated {target.relative_to(ROOT)} from md/AGENTS.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
