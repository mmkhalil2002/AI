"""Generate the installation requirements for one Night Guard role."""

import argparse
from pathlib import Path


REQUIREMENTS = {
    "client": ("requests>=2.31", "PySide6>=6.6", "python-dotenv>=1.0"),
    "server": ("opencv-python>=4.8", "python-dotenv>=1.0"),
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("role", choices=REQUIREMENTS)
    role = parser.parse_args().role

    root = Path(__file__).resolve().parent.parent
    path = root / f"requirements-{role}.txt"
    text = "\n".join(("# Generated by config/generate_requirements.py", *REQUIREMENTS[role], ""))
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"Requirements refreshed: {path}")


if __name__ == "__main__":
    main()
